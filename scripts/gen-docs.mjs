#!/usr/bin/env node
/**
 * Text generated from the tool registry (FR-015, FR-016, FR-020).
 *
 *   node scripts/gen-docs.mjs          write the files
 *   node scripts/gen-docs.mjs --check  fail if any differs, or if the built packages
 *                                      hold a T2 tool, an old route, or a tool's
 *                                      description written outside the registry
 *
 * Writes protocol/capabilities.md, docs/tools.md, llms.txt and the tool table
 * between the markers in README.md. Needs `npm run build` first.
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, extname, join, relative } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
const core = await import(pathToFileURL(join(root, "packages/core/dist/index.js")).href);
const reg = core.defaultRegistry();
const tools = reg.all();
const problems = [];

const GENERATED = "<!-- Generated by scripts/gen-docs.mjs from the tool registry. Do not edit. -->";
const tierName = { none: "—", t1: "T1", t2: "T2" };
const capName = (id) => core.CAPABILITIES.find((c) => c.id === id)?.name ?? id;

function toolTable() {
  const rows = tools.map((t) => {
    const where = t.surfaces.includes("mcp") ? `\`${t.name}\`, \`authoryx ${t.cli}\`` : `\`authoryx ${t.cli}\` only`;
    return `| ${where} | ${t.summary} | ${capName(t.capability)} | ${tierName[t.tier]} | ${t.never} |`;
  });
  return ["| Tool | What it does | Capability | Tier | Never returns |", "| --- | --- | --- | --- | --- |", ...rows].join("\n");
}

const capabilities = `${GENERATED}

# Capabilities

Every tool declares one capability. A host is offered a tool only when its capability is granted to
the agent. \`ask\`, \`run\` and \`fetch\` are always granted; the others are granted by the Authoryx
platform through \`whoami.capabilities\`, and an id the tools do not know is ignored.

| Id | Name | Tier | State | What it allows |
| --- | --- | --- | --- | --- |
${core.CAPABILITIES.map((c) => `| \`${c.id}\` | ${c.name} | ${tierName[c.tier]} | ${c.reserved ? "reserved, no tool yet" : "in this release"} | ${c.summary} |`).join("\n")}

Tiers: **T0, In the chat** — never; no tool puts a value in the conversation. **T1, Out of the chat**
— the value reaches a program on the agent's machine. **T2, Out of the agent's hands** — an Authoryx
tool uses the value for the agent; reserved, switched on per agent from the dashboard by a later
release.
`;

const toolsDoc = `${GENERATED}

# Tools

${toolTable()}

## Inputs

${tools
  .map((t) => {
    const props = Object.entries(t.input.properties ?? {});
    const req = new Set(t.input.required ?? []);
    const lines = props.length
      ? props.map(([k, v]) => `- \`${k}\`${req.has(k) ? " (required)" : ""}: ${v.description ?? v.type ?? ""}`).join("\n")
      : "- none";
    return `### ${t.surfaces.includes("mcp") ? t.name : `authoryx ${t.cli}`}\n\n${t.summary}\n\nReturns ${t.returns}.\n\n${lines}`;
  })
  .join("\n\n")}
`;

const llms = `# Authoryx agent tools

> An AI agent asks to use a secret shared into one of its circles, with a reason; the secret's owner approves or denies on the Authoryx dashboard; the value goes to a program, and no MCP tool returns it.

## Tools

${tools.map((t) => `- ${t.surfaces.includes("mcp") ? t.name : `authoryx ${t.cli}`}: ${t.summary}`).join("\n")}

## Docs

- [README](https://github.com/AutumLabs/Authoryx#readme)
- [AGENTS.md](https://github.com/AutumLabs/Authoryx/blob/main/AGENTS.md)
- [Agent API](https://github.com/AutumLabs/Authoryx/blob/main/protocol/agent-api.md)
- [Capabilities](https://github.com/AutumLabs/Authoryx/blob/main/protocol/capabilities.md)
`;

function emit(rel, text) {
  const p = join(root, rel);
  const cur = existsSync(p) ? readFileSync(p, "utf8") : null;
  if (cur === text) return;
  if (check) problems.push(`${rel} is out of date; run node scripts/gen-docs.mjs`);
  else {
    mkdirSync(dirname(p), { recursive: true });
    writeFileSync(p, text);
  }
}

emit("protocol/capabilities.md", capabilities);
emit("docs/tools.md", toolsDoc);
emit("llms.txt", llms);
const readmePath = join(root, "README.md");
const readme = readFileSync(readmePath, "utf8");
const START = "<!-- tools:start -->";
const END = "<!-- tools:end -->";
if (readme.includes(START) && readme.includes(END)) {
  const next = readme.replace(new RegExp(`${START}[\\s\\S]*?${END}`), `${START}\n${toolTable()}\n${END}`);
  emit("README.md", next);
} else problems.push("README.md has no tools:start / tools:end markers");

if (check) {
  // AC-044: no T2 tool in what is published.
  for (const t of tools) if (t.tier === "t2") problems.push(`packages: ${t.name} is a T2 tool; none ships in this release`);
  // Old routes of the earlier private API must not reappear.
  const OLD = /\/v1\/os\/(keys|folders|intents|exports|notes)\b/;
  const walk = (dir, fn) => {
    if (!existsSync(dir)) return;
    for (const n of readdirSync(dir)) {
      if (n === "node_modules" || n === ".git") continue;
      const p = join(dir, n);
      statSync(p).isDirectory() ? walk(p, fn) : fn(p);
    }
  };
  for (const pkg of readdirSync(join(root, "packages"))) {
    walk(join(root, "packages", pkg, "dist"), (p) => {
      if (OLD.test(readFileSync(p, "utf8"))) problems.push(`${relative(root, p)}: an old /v1/os route`);
    });
  }
  // AC-055: a tool's description lives in the registry and generated files only.
  const allowed = new Set(["packages/core/src/tools/index.ts", "README.md", "docs/tools.md", "llms.txt", "protocol/capabilities.md"]);
  const TEXT = new Set([".md", ".ts", ".mjs", ".js", ".json", ".py", ".txt"]);
  walk(root, (p) => {
    const rel = relative(root, p).split("\\").join("/");
    if (allowed.has(rel) || rel.includes("/dist/") || !TEXT.has(extname(p)) || rel.endsWith("package-lock.json")) return;
    const text = readFileSync(p, "utf8");
    for (const t of tools) if (text.includes(t.summary)) problems.push(`${rel}: repeats the description of ${t.name}; it belongs in the registry`);
  });
}

if (problems.length) {
  console.error(`gen-docs: ${problems.length} problem(s)\n${problems.map((p) => `  ${p}`).join("\n")}`);
  process.exit(1);
}
console.log(check ? "gen-docs: generated text is current" : "gen-docs: wrote protocol/capabilities.md, docs/tools.md, llms.txt and the README tool table");
